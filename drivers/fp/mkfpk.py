#!/usr/bin/env python3
"""The float engine's constants and series (drivers/fp/fpk.inc).

    python3 drivers/fp/mkfpk.py > drivers/fp/fpk.inc

Standard constants and Taylor coefficients (1/n!, 1/(2k+1)), written in
the Spectrum's five-byte format: exponent byte (bias 128) and a 32-bit
mantissa 0.1m...m whose leading 1 is replaced by the sign.  Nothing here
comes from the Spectrum ROM: this is a clean-room engine.
"""
import math
from fractions import Fraction

PI = Fraction(math.pi)        # 53 bits: well beyond the format's 32


def five(v):
    v = Fraction(v)
    if v == 0:
        return [0, 0, 0, 0, 0]
    if v.denominator == 1 and abs(v) <= 65535:
        n = int(v)
        w = n & 0xFFFF
        return [0, 0xFF if n < 0 else 0, w & 255, w >> 8, 0]
    s, a = (0x80, -v) if v < 0 else (0, v)
    e = 0
    while a >= 1:
        a /= 2
        e += 1
    while a < Fraction(1, 2):
        a *= 2
        e -= 1
    m = round(a * 2 ** 32)
    if m == 2 ** 32:
        m >>= 1
        e += 1
    return [e + 128, (m >> 24 & 0x7F) | s, m >> 16 & 255, m >> 8 & 255, m & 255]


def split(v, bits=24):
    """v = hi + lo, hi with `bits` significant bits: n * hi is exact."""
    v = Fraction(v)
    e = 0
    a = abs(v)
    while a >= 1:
        a /= 2
        e += 1
    while a < Fraction(1, 2):
        a *= 2
        e -= 1
    hi = Fraction(round(a * 2 ** bits), 2 ** bits) * Fraction(2) ** e * (1 if v > 0 else -1)
    return hi, v - hi


LN2 = Fraction(math.log(2))
LN2HI, LN2LO = split(LN2)
PIO2HI, _r = split(PI / 2, 16)          # three parts: q * each is exact
PIO2MI, PIO2LO = split(_r, 16)           # for q up to 65535
SQRT3 = Fraction(math.sqrt(3))

CONSTS = [
    ('ZERO', 0), ('ONE', 1), ('HALF', Fraction(1, 2)), ('INVLN2', 1 / LN2),
    ('LN2HI', LN2HI), ('LN2LO', LN2LO), ('TWOOPI', 2 / PI), ('PIO2HI', PIO2HI),
    ('PIO2LO', PIO2LO), ('PIO2', PI / 2), ('PI6', PI / 6), ('SQRT3', SQRT3),
    ('TAN15', 2 - SQRT3), ('PIO2MI', PIO2MI),
]


def fact(n):
    return math.factorial(n)


# series, highest degree first (Horner)
POLYS = [
    # e^r = sum r^k / k!, |r| <= ln2/2
    ('EXP', [Fraction(1, fact(k)) for k in range(11, -1, -1)]),
    # ln m = s * sum 2 z^k / (2k+1), s = (m-1)/(m+1), z = s^2
    ('LN', [Fraction(2, 2 * k + 1) for k in range(7, -1, -1)]),
    # sin r = r * sum (-1)^k z^k / (2k+1)!, z = r^2, |r| <= pi/4
    ('SIN', [Fraction((-1) ** k, fact(2 * k + 1)) for k in range(6, -1, -1)]),
    # cos r = sum (-1)^k z^k / (2k)!
    ('COS', [Fraction((-1) ** k, fact(2 * k)) for k in range(7, -1, -1)]),
    # atan t = t * sum (-1)^k z^k / (2k+1), |t| <= 2 - sqrt 3
    ('ATAN', [Fraction((-1) ** k, 2 * k + 1) for k in range(8, -1, -1)]),
]


def db(bs):
    return 'db ' + ','.join('0%02Xh' % b for b in bs)


def main():
    print('; generated by drivers/fp/mkfpk.py: constants and series, five bytes each')
    for i, (name, _) in enumerate(CONSTS):
        print('C_%-7s equ 80h+%d' % (name, i))
    print('fpk:')
    for name, v in CONSTS:
        print('        %s  ; %s' % (db(five(v)), name))
    for i, (name, _) in enumerate(POLYS):
        print('P_%-7s equ %d' % (name, i))
    print('fpptab:')
    for name, _ in POLYS:
        print('        dw fpp_%s' % name)
    for name, cs in POLYS:
        print('fpp_%s: db %d' % (name, len(cs)))
        for c in cs:
            print('        %s' % db(five(c)))


if __name__ == '__main__':
    main()
