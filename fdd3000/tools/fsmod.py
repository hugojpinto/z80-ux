#!/usr/bin/env python3
"""File system modules: types that ZX-UX loads at mount time (fsmod.asm).

    fsmod.py SOURCE NAME OUT       a module from SOURCE, after a build

A module's source is assembled on its own, against the kernel's ABI: the
symbols in ABI below, written by the build to build/fdd3000/kabi.inc as
plain EQUs.  Its first bytes must be its vector of operations (vfs.asm
FO_MOUNT .. FO_SYNC), then whatever code and data it needs; it may use
ds, but not ALIGN, nor "high" or "low" of its own labels.

It is assembled twice, at 0000h and at 0101h: a word that differs by
0101h between the two is an address in the module - a relocation; any
other difference is an error.  The file (fsmod.asm has the format):

    "ZXFM", ABI.w, image length.w, relocations.w, name (8)
    the image (assembled at 0000h)
    the relocations, a word each: offsets in the image

ABI is a checksum of the ABI symbols and their values: the kernel carries
its own (KABI) and loads no module made for another build.
"""
import os
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)
ROOT = os.path.dirname(PORT)

# What a module may use of the kernel: routines, variables, constants.  A
# change to any of their values changes ABI.
ABI = [
    # helpers (unix.asm)
    'addhla', 'cphlde', 'minhlde', 'div32', 'ldind',
    # the buffer cache and the drives (fd.asm)
    'bget', 'bflush', 'bdirty', 'binval',
    # i-nodes and the clock (fs.asm, zx.asm)
    'iadv', 'isize', 'setmtim',
    # the mount layer (vfs.asm)
    'vmhi', 'vdrv',
    # the transfer of the system call (readi, writei)
    'u_base', 'u_count', 'u_nread', 'u_off',
    # the mount entry: fields of IY
    'M_TYPE', 'M_DRV', 'M_BASE', 'M_BLKS', 'M_INOS', 'M_BMAP', 'M_ITAB',
    'M_DATA', 'M_COVER',
    # the in-core i-node
    'I_SIZE',
    # errors
    'EIO', 'EINVAL', 'ENOSPC', 'EFBIG', 'ENOENT',
]


def fletcher16(data):
    a = b = 0
    for x in data:
        a = (a + x) % 255
        b = (b + a) % 255
    return b << 8 | a


def abi(sym):
    """The ABI symbols' values and their checksum (never 0: 0 is a
    kernel built without it)."""
    vals = {}
    for name in ABI:
        if name not in sym:
            raise KeyError('ABI symbol %s is not in the kernel' % name)
        vals[name] = sym[name]
    text = ''.join('%s=%04X;' % (n, vals[n]) for n in sorted(vals))
    return vals, fletcher16(text.encode()) or 1


def write_kabi(path, sym):
    vals, stamp = abi(sym)
    with open(path, 'w') as f:
        f.write('; generated by fdd3000/tools/fsmod.py: the kernel ABI\n')
        f.write('KABI equ 0%04Xh\n' % stamp)
        for n in ABI:
            f.write('%-8s equ 0%04Xh\n' % (n, vals[n]))
    return stamp


def assemble(sjasmplus, kabi_inc, source, org, work):
    os.makedirs(work, exist_ok=True)
    main = os.path.join(work, 'mod_%04x.asm' % org)
    out = os.path.join(work, 'mod_%04x.bin' % org)
    with open(main, 'w') as f:
        f.write('        DEVICE NOSLOT64K\n'
                '        include "%s"\n'
                '        org 0%04Xh\n'
                'modbeg:\n'
                '        include "%s"\n'
                'modend:\n'
                '        SAVEBIN "%s", modbeg, modend-modbeg\n'
                % (kabi_inc, org, os.path.abspath(source), out))
    r = subprocess.run([sjasmplus, '--nologo', '--msg=war', '--fullpath=off', main],
                       cwd=os.path.dirname(os.path.abspath(source)),
                       capture_output=True, text=True)
    if r.returncode or 'error' in (r.stdout + r.stderr).lower():
        raise ValueError('%s:\n%s%s' % (source, r.stdout, r.stderr))
    with open(out, 'rb') as f:
        return f.read()


def relocations(a, b, delta=0x0101):
    if len(a) != len(b):
        raise ValueError('the two assemblies differ in length')
    rel, i = [], 0
    while i < len(a):
        if a[i] == b[i]:
            i += 1
            continue
        if i + 1 < len(a):
            wa = a[i] | a[i + 1] << 8
            wb = b[i] | b[i + 1] << 8
            if (wb - wa) & 0xFFFF == delta:
                rel.append(i)
                i += 2
                continue
        raise ValueError('byte %04Xh: not a whole address (high, low or '
                         'ALIGN of a label?)' % i)
    return rel


def build(sjasmplus, kabi_inc, source, name, work):
    """The module file's bytes."""
    with open(kabi_inc) as f:
        stamp = [int(line.split()[2].rstrip('h'), 16) for line in f
                 if line.startswith('KABI ')][0]
    a = assemble(sjasmplus, kabi_inc, source, 0x0000, work)
    b = assemble(sjasmplus, kabi_inc, source, 0x0101, work)
    rel = relocations(a, b)
    nm = name.encode()
    if not 0 < len(nm) <= 8 or b'/' in nm:
        raise ValueError('a type name is 1 to 8 letters, no /')
    hdr = b'ZXFM' + struct.pack('<HHH', stamp, len(a), len(rel)) + nm.ljust(8, b'\0')
    return hdr + a + b''.join(struct.pack('<H', r) for r in rel)


def main():
    if len(sys.argv) != 4:
        print(__doc__.split('\n\n')[1])
        return 2
    source, name, out = sys.argv[1:]
    sjasmplus = os.environ.get('SJASMPLUS', os.path.join(HERE, 'bin', 'sjasmplus'))
    kabi_inc = os.path.join(ROOT, 'build', 'fdd3000', 'kabi.inc')
    data = build(sjasmplus, kabi_inc, source, name,
                 os.path.join(ROOT, 'build', 'fdd3000', 'mod'))
    with open(out, 'wb') as f:
        f.write(data)
    print('%s: %s, %d bytes' % (out, name, len(data)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
